"""Load a host's branding from the database for the PDF and for on-screen tickets."""

from sqlmodel import Session, select

from app.models import Branding
from app.services.branding import on_color
from app.services.pdf import BrandStyle


def branding_row(session: Session, owner_id: int) -> Branding | None:
    return session.exec(select(Branding).where(Branding.owner_id == owner_id)).first()


def logo_path(settings, row: Branding | None):
    if row is None or not row.logo_filename:
        return None
    path = settings.branding_dir / row.logo_filename  # filenames are generated by the server
    return path if path.is_file() else None


def brand_style(session: Session, settings, owner_id: int) -> BrandStyle | None:
    """For the PDF. None means the host hasn't set any branding."""
    row = branding_row(session, owner_id)
    if row is None:
        return None
    path = logo_path(settings, row)
    return BrandStyle(
        accent=row.accent_color or None,
        header_text=row.header_text,
        footer_text=row.footer_text,
        logo_png=path.read_bytes() if path else None,
    )


def brand_context(session: Session, settings, owner_id: int, game_code: str) -> dict | None:
    """For templates: an accent colour (with a readable text colour) and a public logo URL."""
    row = branding_row(session, owner_id)
    if row is None:
        return None
    has_logo = logo_path(settings, row) is not None
    if not row.accent_color and not has_logo:
        return None
    return {
        "accent": row.accent_color or None,
        "on_accent": on_color(row.accent_color) if row.accent_color else None,
        "logo_url": f"/brand/{game_code}/logo?v={row.logo_filename}" if has_logo else None,
    }
